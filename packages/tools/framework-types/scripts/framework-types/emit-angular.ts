import { formControlModel, type DiscoveredPackage } from './manifests.ts'

/**
 * The `ControlValueAccessor` directives of `@c2n/angular`.
 *
 * Angular's built-in accessors match `input`, `select` and `textarea` only, so a form-associated custom element
 * is invisible to `ngModel` and `formControlName` however correct its `ElementInternals` are. One directive per
 * value shape — `value` for the text-like controls, `checked` for the toggles — restores that, and the tag lists
 * come from the manifests so a new form control is covered as soon as it ships.
 *
 * The selectors have to be string literals for the Angular compiler to read them, which is why this file is
 * generated rather than assembling them at runtime.
 */
export function emitAngular(packages: DiscoveredPackage[]): string {
  const value: string[] = []
  const checked: string[] = []

  for (const pkg of packages) {
    for (const element of pkg.elements) {
      const model = formControlModel(element)
      if (model === 'checked') checked.push(element.tagName)
      else if (model === 'value') value.push(element.tagName)
    }
  }

  const selector = (tags: string[]) => tags.flatMap((tag) => [`${tag}[ngModel]`, `${tag}[formControl]`, `${tag}[formControlName]`]).join(', ')

  return `// GENERATED by @c2n/framework-types. Do not edit by hand.
import { Directive, ElementRef, forwardRef, inject } from '@angular/core'
import { NG_VALUE_ACCESSOR, type ControlValueAccessor } from '@angular/forms'

/** The element half of a c2 form control, as far as an accessor is concerned. */
interface FormControlElement extends HTMLElement {
  value?: unknown
  checked?: boolean
  disabled?: boolean
}

/**
 * Binds \`ngModel\` / \`formControl\` / \`formControlName\` to the \`value\` of a c2 form control.
 *
 * The control is read on \`input\`, which every one of these components fires when its value changes, and marked
 * touched on \`focusout\` — \`blur\` does not cross the shadow boundary from the inner control.
 *
 * A \`c2-select\` carries its selection as a \`string[]\`, so that is what the bound model receives.
 */
@Directive({
  selector: '${selector(value)}',
  host: {
    '(input)': 'handleInput()',
    '(focusout)': 'handleTouched()',
  },
  providers: [{ provide: NG_VALUE_ACCESSOR, useExisting: forwardRef(() => C2ValueAccessor), multi: true }],
})
export class C2ValueAccessor implements ControlValueAccessor {
  private readonly element = inject<ElementRef<FormControlElement>>(ElementRef).nativeElement
  private notifyChange: (value: unknown) => void = () => {}
  private notifyTouched: () => void = () => {}

  writeValue(value: unknown): void {
    this.element.value = value ?? (Array.isArray(this.element.value) ? [] : '')
  }

  registerOnChange(fn: (value: unknown) => void): void {
    this.notifyChange = fn
  }

  registerOnTouched(fn: () => void): void {
    this.notifyTouched = fn
  }

  setDisabledState(isDisabled: boolean): void {
    this.element.disabled = isDisabled
  }

  protected handleInput(): void {
    this.notifyChange(this.element.value)
  }

  protected handleTouched(): void {
    this.notifyTouched()
  }
}

/** The same, for the toggles: the model is the \`checked\` state and the control is read on \`change\`. */
@Directive({
  selector: '${selector(checked)}',
  host: {
    '(change)': 'handleChange()',
    '(focusout)': 'handleTouched()',
  },
  providers: [{ provide: NG_VALUE_ACCESSOR, useExisting: forwardRef(() => C2CheckedAccessor), multi: true }],
})
export class C2CheckedAccessor implements ControlValueAccessor {
  private readonly element = inject<ElementRef<FormControlElement>>(ElementRef).nativeElement
  private notifyChange: (value: boolean) => void = () => {}
  private notifyTouched: () => void = () => {}

  writeValue(value: unknown): void {
    this.element.checked = Boolean(value)
  }

  registerOnChange(fn: (value: boolean) => void): void {
    this.notifyChange = fn
  }

  registerOnTouched(fn: () => void): void {
    this.notifyTouched = fn
  }

  setDisabledState(isDisabled: boolean): void {
    this.element.disabled = isDisabled
  }

  protected handleChange(): void {
    this.notifyChange(Boolean(this.element.checked))
  }

  protected handleTouched(): void {
    this.notifyTouched()
  }
}

/** Every accessor, for a component's \`imports\` array. */
export const C2_FORM_ACCESSORS = [C2ValueAccessor, C2CheckedAccessor] as const
`
}
