/**
 * Keeps the guidance coding agents read (Claude Code and Codex) true to the repository. Prose rules rot silently: a
 * moved file, a skill updated for one agent and not the other. This gate fails on:
 *
 * - a repository path named in backticks in a guidance file (`CLAUDE.md` at any depth, `docs/agents/*.md`, every
 *   skill's `SKILL.md`, the subagents in `.claude/agents/`) that does not exist. A path resolves against the repository root, then against the guidance
 *   file's own directory (a nested `CLAUDE.md` names `src/…` relative to its package). Placeholders (`<name>`, `*`,
 *   `{…}`, `…`), git-ignored build output (`dist/`, `data/registry.json`), paths in `OUTSIDE_REPO` and vendored
 *   skills (spec-kit's, regenerated by its installer) are skipped;
 * - a nested `CLAUDE.md` without an `AGENTS.md` symlink beside it, or missing from the root index;
 * - a skill present for one agent only, or present for both as two separate copies (`.claude/skills/<name>` and
 *   `.agents/skills/<name>` must resolve to the same folder).
 *
 * Run: `npm run check:agent-docs` (a `deploy.yml` gate).
 */
import { execFileSync } from 'node:child_process'
import { existsSync, lstatSync, readdirSync, readFileSync, readlinkSync, realpathSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const problems = []
const rel = (file) => relative(root, file)

const tracked = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { cwd: root, encoding: 'utf8' })
  .split('\0')
  // A guide deleted but not yet committed is still in the index.
  .filter((file) => file && existsSync(join(root, file)))
const nestedGuides = tracked.filter((file) => file.endsWith('/CLAUDE.md') && !file.includes('node_modules/'))
const agentDocs = tracked.filter((file) => file.startsWith('docs/agents/') && file.endsWith('.md'))
const skillFiles = ['.claude/skills', '.agents/skills'].flatMap((dir) =>
  readdirSync(join(root, dir))
    .map((name) => join(dir, name, 'SKILL.md'))
    .filter((file) => existsSync(join(root, file))),
)
const subagents = existsSync(join(root, '.claude/agents'))
  ? readdirSync(join(root, '.claude/agents'))
      .filter((name) => name.endsWith('.md'))
      .map((name) => join('.claude/agents', name))
  : []
// A skill linked into both folders is one file: check it once.
const guides = [...new Set(['CLAUDE.md', ...nestedGuides, ...agentDocs, ...skillFiles, ...subagents].map((file) => rel(realpathSync(join(root, file)))))]

// --- Paths named in guidance -------------------------------------------------------------------------------------

const TOP_LEVEL = new Set(readdirSync(root).filter((name) => name !== 'node_modules' && name !== '.git'))
const PLACEHOLDER = /[<>*{}…$]|\.\.\.|\s/
// Paths a guide names in another project, not this one: what `c2n-skill install` writes into a consumer's repo.
const OUTSIDE_REPO = new Set(['.github/skills', '.github/copilot-instructions.md'])
const isVendored = (text) => /^\s*author:\s*['"]?github-spec-kit/m.test(text)

function isIgnored(path) {
  try {
    execFileSync('git', ['check-ignore', '-q', '--no-index', path], { cwd: root })
    return true
  } catch {
    return false
  }
}

for (const guide of guides) {
  const text = readFileSync(join(root, guide), 'utf8')
  if (isVendored(text)) continue
  const guideDir = dirname(guide)
  const seen = new Set()
  for (const [, raw] of text.matchAll(/`([^`\n]+)`/g)) {
    const path = raw.replace(/[:#].*$/, '').replace(/\/$/, '')
    if (seen.has(path) || OUTSIDE_REPO.has(path) || !path.includes('/') || PLACEHOLDER.test(path) || /^(@|https?:|\/|\.\.?\/)/.test(path)) continue
    seen.add(path)
    const firstSegment = path.split('/')[0]
    // Only judge what is meant as a repository path: rooted at a top-level entry, or something the guide's own
    // directory holds the first segment of (`src/…` in `apps/ui/CLAUDE.md`, `scripts/…` in a package's guide).
    // Package specifiers (`lit/decorators.js`) and URL routes (`/components/<id>`) match neither.
    if (!TOP_LEVEL.has(firstSegment) && !existsSync(join(root, guideDir, firstSegment))) continue
    const candidates = [path, join(guideDir, path)]
    if (candidates.some((candidate) => existsSync(join(root, candidate)) || isIgnored(candidate))) continue
    problems.push(`${guide}: \`${raw}\` does not exist`)
  }
}

// --- Nested guidance: AGENTS.md links and the root index -----------------------------------------------------------

const rootGuide = readFileSync(join(root, 'CLAUDE.md'), 'utf8')
for (const guide of nestedGuides) {
  const agents = join(root, dirname(guide), 'AGENTS.md')
  if (!existsSync(agents) || !lstatSync(agents).isSymbolicLink() || readlinkSync(agents) !== 'CLAUDE.md')
    problems.push(`${dirname(guide)}/AGENTS.md: missing, or not a symlink to CLAUDE.md (Codex reads AGENTS.md)`)
  if (!rootGuide.includes(`\`${guide}\``)) problems.push(`CLAUDE.md: the "Where the rest lives" table does not list \`${guide}\``)
}
for (const doc of agentDocs) if (!rootGuide.includes(`\`${doc}\``)) problems.push(`CLAUDE.md: the "Where the rest lives" table does not list \`${doc}\``)
const rootAgents = join(root, 'AGENTS.md')
if (!existsSync(rootAgents) || !lstatSync(rootAgents).isSymbolicLink() || readlinkSync(rootAgents) !== 'CLAUDE.md')
  problems.push('AGENTS.md: not a symlink to CLAUDE.md')

// --- One copy of every skill ---------------------------------------------------------------------------------------

const skillNames = (dir) => new Set(readdirSync(join(root, dir)).filter((name) => existsSync(join(root, dir, name, 'SKILL.md'))))
const claudeSkills = skillNames('.claude/skills')
const codexSkills = skillNames('.agents/skills')
for (const name of new Set([...claudeSkills, ...codexSkills])) {
  if (!claudeSkills.has(name)) problems.push(`.claude/skills/${name}: missing (link it to .agents/skills/${name})`)
  else if (!codexSkills.has(name)) problems.push(`.agents/skills/${name}: missing (link it to .claude/skills/${name})`)
  else if (realpathSync(join(root, '.claude/skills', name)) !== realpathSync(join(root, '.agents/skills', name)))
    problems.push(`skill ${name}: .claude/skills and .agents/skills hold two copies; keep one and symlink the other`)
}

if (problems.length) {
  console.error(`\n[agent-docs] ${problems.length} problem(s) in the guidance agents read:\n`)
  for (const problem of problems) console.error(`  - ${problem}`)
  process.exit(1)
}
console.log(`[agent-docs] ${guides.length} guidance files and ${claudeSkills.size} skills are consistent`)
