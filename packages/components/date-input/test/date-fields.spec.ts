test('resets to its authored date, restores disabled fieldsets and keeps read-only values', async ({ page, renderScenario }) => {
  await renderScenario('<form><fieldset><c2-date-fields name="due" order="dmy" value="2026-09-15" aria-label="Due"></c2-date-fields></fieldset></form>')
  const host = page.locator('c2-date-fields')
  await field(host, 'Day').fill('20')
  await expect(host).toHaveJSProperty('value', '2026-09-20')
  await page.locator('form').evaluate((form) => (form as HTMLFormElement).reset())
  await expect(field(host, 'Day')).toHaveValue('15')
  await expect(host).toHaveJSProperty('value', '2026-09-15')
  await page.locator('form > fieldset').evaluate((fieldset) => ((fieldset as HTMLFieldSetElement).disabled = true))
  await expect(field(host, 'Day')).toBeDisabled()
  await expect.poll(() => formValue(page, 'due')).toBe(null)
  await page.locator('form > fieldset').evaluate((fieldset) => ((fieldset as HTMLFieldSetElement).disabled = false))
  await props(host, { readOnly: true })
  await expect(field(host, 'Year')).toHaveAttribute('readonly', '')
  await expect.poll(() => formValue(page, 'due')).toBe('2026-09-15')
})

test('moves through the fields with Tab and focuses the first one from focus()', async ({ page, renderScenario }) => {
  await renderScenario('<c2-date-fields order="dmy" autocomplete="bday" aria-label="Date of birth"></c2-date-fields>')
  const host = page.locator('c2-date-fields')
  await host.evaluate((element) => (element as HTMLElement).focus())
  await expect(field(host, 'Day')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(field(host, 'Month')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(field(host, 'Year')).toBeFocused()
  await expect(field(host, 'Day')).toHaveAttribute('autocomplete', 'bday-day')
  await expect(field(host, 'Year')).toHaveAttribute('autocomplete', 'bday-year')
  await expect(field(host, 'Day')).toHaveAttribute('inputmode', 'numeric')
})

