test('names the wrong part once focus leaves the group', async ({ page, renderScenario }) => {
  await renderScenario('<c2-date-fields order="dmy" aria-label="Date of birth" help="For example, 27 3 2007"></c2-date-fields><button>Next</button>')
  const host = page.locator('c2-date-fields')
  const message = host.locator('.supporting-text')
  await field(host, 'Day').fill('27')
  await field(host, 'Month').fill('13')
  await field(host, 'Year').fill('2007')
  // Still inside the group: the hint stays.
  await expect(message).toHaveText('For example, 27 3 2007')
  await page.keyboard.press('Tab')
  await expect(message).toHaveText('Month must be a number from 1 to 12')
  await expect(message).toHaveClass(/error/)
  await expect(field(host, 'Month')).toHaveAttribute('aria-invalid', 'true')
  await expect(field(host, 'Day')).not.toHaveAttribute('aria-invalid')
  await expect(field(host, 'Month')).toHaveAccessibleDescription('Month must be a number from 1 to 12')
  await accessible(page)

  await field(host, 'Month').fill('2')
  await field(host, 'Day').fill('31')
  await expect(message).toHaveText('Date must be a real date')
  await expect(field(host, 'Day')).toHaveAttribute('aria-invalid', 'true')
  await field(host, 'Day').fill('')
  await expect(message).toHaveText('Date must include a day')
  await field(host, 'Year').fill('')
  await expect(message).toHaveText('Enter a full date')
  await expect(field(host, 'Year')).toHaveAttribute('aria-invalid', 'true')
  await field(host, 'Day').fill('3')
  await field(host, 'Year').fill('07')
  await expect(message).toHaveText('Year must have 4 digits')
  await field(host, 'Year').fill('2007')
  await expect(message).toHaveText('For example, 27 3 2007')
  await expect(host).toHaveJSProperty('value', '2007-02-03')
})

test('reports required, min and max through form validity', async ({ page, renderScenario }) => {
  await renderScenario('<form><c2-date-fields name="d" order="dmy" required min="2000-01-01" max="2009-12-31" aria-label="Date"></c2-date-fields></form>')
  const host = page.locator('c2-date-fields')
  expect(await valid(host)).toBe(false)
  await expect(host).toHaveJSProperty('validity.valueMissing', true)
  // An invalid form shows the message without the group being left.
  await page.locator('form').evaluate((form) => (form as HTMLFormElement).requestSubmit())
  await expect(host.locator('.supporting-text')).toHaveText('Enter a date')
  await field(host, 'Day').fill('1')
  await field(host, 'Month').fill('1')
  await field(host, 'Year').fill('1999')
  await expect(host.locator('.supporting-text')).toHaveText('Date must be on or after January 1, 2000')
  await expect(host).toHaveJSProperty('validity.customError', true)
  await expect(host).toHaveJSProperty('value', '1999-01-01')
  await field(host, 'Year').fill('2010')
  await expect(host.locator('.supporting-text')).toHaveText('Date must be on or before December 31, 2009')
  await field(host, 'Year').fill('2005')
  await expect.poll(() => valid(host)).toBe(true)
  await host.evaluate((element) => (element as HTMLElement & { setCustomValidity(m: string): void }).setCustomValidity('Taken'))
  await expect.poll(() => valid(host)).toBe(false)
  await expect(host).toHaveJSProperty('validationMessage', 'Taken')
  await expect(host.locator('.supporting-text')).toHaveText('Taken')
  await expect(host.locator('input[aria-invalid="true"]')).toHaveCount(3)
})

test('shows error-text while error is set, in place of slotted help', async ({ page, renderScenario }) => {
  await renderScenario(
    '<c2-date-fields error error-text="Must match your passport" aria-label="Date"><span slot="supporting-text">Slotted help</span></c2-date-fields>',
  )
  const host = page.locator('c2-date-fields')
  await expect(host.locator('.supporting-text')).toHaveClass(/error/)
  await expect(host.locator('.supporting-text')).toContainText('Must match your passport')
  await expect(host.getByText('Slotted help')).toBeHidden()
  await expect(host.locator('input[aria-invalid="true"]')).toHaveCount(3)
  await props(host, { error: false })
  await expect(host.locator('input[aria-invalid="true"]')).toHaveCount(0)
  await expect(host.getByText('Slotted help')).toBeVisible()
  // A part-naming message also replaces the slotted help.
  await field(host, 'Month').fill('13')
  await field(host, 'Month').blur()
  await expect(host.locator('.supporting-text')).toContainText('Enter a full date')
  await expect(host.getByText('Slotted help')).toBeHidden()
})

