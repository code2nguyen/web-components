import type { DiscoveredPackage } from './manifests.ts'

/**
 * Editor metadata for the templates TypeScript never sees: plain `.html`, Angular templates (whose `c2-*` tags
 * are opaque under `CUSTOM_ELEMENTS_SCHEMA`) and Vue SFCs.
 *
 * `html-custom-data.json` is VS Code's format — point `html.customData` at it — and Volar reads it for Vue
 * templates too. `web-types.json` is the JetBrains equivalent; a package that names it in `package.json`
 * (`"web-types": "./web-types.json"`) is picked up by WebStorm with no configuration at all.
 */
export function emitHtmlCustomData(packages: DiscoveredPackage[], version: string): string {
  const tags = packages.flatMap((pkg) =>
    pkg.elements.map((element) => ({
      name: element.tagName,
      description: description(element.description, pkg.name),
      references: [{ name: `${pkg.name} on npm`, url: `https://www.npmjs.com/package/${pkg.name}` }],
      attributes: element.attributes.map((attribute) => ({
        name: attribute.name,
        description: [attribute.description, attribute.default === undefined ? undefined : `Default: \`${attribute.default}\``].filter(Boolean).join('\n\n'),
        values: attributeValues(attribute.type),
      })),
    })),
  )

  return `${JSON.stringify({ version: 1.1, $comment: `GENERATED by @c2n/framework-types@${version}. Do not edit by hand.`, tags }, null, 2)}\n`
}

export function emitWebTypes(packages: DiscoveredPackage[], version: string): string {
  const elements = packages.flatMap((pkg) =>
    pkg.elements.map((element) => ({
      name: element.tagName,
      description: description(element.description, pkg.name),
      attributes: element.attributes.map((attribute) => ({
        name: attribute.name,
        description: attribute.description,
        default: attribute.default,
        value: { type: attribute.type ?? 'any', kind: 'expression' as const },
      })),
      js: {
        properties: element.attributes
          .filter((attribute) => attribute.fieldName !== attribute.name)
          .map((attribute) => ({
            name: attribute.fieldName,
            description: attribute.description,
            value: { type: attribute.type ?? 'any', kind: 'expression' as const },
          })),
        events: element.events.map((event) => ({ name: event.name, description: event.description, value: { type: event.type, kind: 'expression' as const } })),
      },
    })),
  )

  return `${JSON.stringify(
    {
      $schema: 'https://raw.githubusercontent.com/JetBrains/web-types/master/schema/web-types.json',
      name: '@c2n/framework-types',
      version,
      description: 'GENERATED by @c2n/framework-types. Do not edit by hand.',
      'description-markup': 'markdown',
      contributions: { html: { elements } },
    },
    null,
    2,
  )}\n`
}

function description(text: string | undefined, pkg: string): string {
  // Only the first paragraph: an editor tooltip is not the place for a component's whole doc comment.
  const summary = (text ?? '').split('\n\n')[0].trim()
  return summary ? `${summary}\n\n\`${pkg}\`` : `\`${pkg}\``
}

/** A union of string literals in the manifest becomes the attribute's completion list. */
function attributeValues(type: string | undefined): { name: string }[] | undefined {
  if (!type || !type.includes('|')) return undefined
  const parts = type.split('|').map((part) => part.trim())
  if (!parts.every((part) => /^'[^']*'$/.test(part))) return undefined
  return parts.map((part) => ({ name: part.slice(1, -1) }))
}
