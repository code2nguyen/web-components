/**
 * Icon generator for `@c2n/phosphor-icons`.
 *
 * Reads the catalog and six SVG weights shipped by `@phosphor-icons/core`, then emits one Lit
 * custom element per icon into `src/icons/<name>.ts`, plus the barrel and icon-name helpers.
 *
 * Run with `npm run generate -w packages/icons/phosphor-icons` (Node 24 type stripping).
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const TAG_PREFIX = 'c2-phosphor-'
const WEIGHTS = ['regular', 'thin', 'light', 'bold', 'fill', 'duotone'] as const

const require = createRequire(import.meta.url)
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const srcDir = join(packageRoot, 'src')
const iconsOutDir = join(srcDir, 'icons')
const upstreamRegularIcon = require.resolve('@phosphor-icons/core/regular/acorn.svg')
const upstreamRoot = resolve(dirname(upstreamRegularIcon), '../..')
const upstreamVersion: string = JSON.parse(readFileSync(join(upstreamRoot, 'package.json'), 'utf8')).version
const sourceLabel = `@phosphor-icons/core@${upstreamVersion}`
const header = `// GENERATED by scripts/icon-generator from ${sourceLabel}. Do not edit by hand.`
const svgWrapper = /^<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/

interface IconSource {
  name: string
  pascalName: string
  bodies: Record<(typeof WEIGHTS)[number], string>
}

function toPascalCase(name: string): string {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
}

function toTemplateLiteralBody(markup: string): string {
  return markup.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function readIconBody(name: string, weight: (typeof WEIGHTS)[number]): string {
  const fileName = weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`
  const filePath = join(upstreamRoot, 'assets', weight, fileName)
  const svg = readFileSync(filePath, 'utf8').trim()
  const match = svgWrapper.exec(svg)
  if (!match) throw new Error(`[icon-generator] ${filePath}: could not parse SVG`)
  return match[1].trim()
}

function readIconSources(): IconSource[] {
  return readdirSync(join(upstreamRoot, 'assets', 'regular'))
    .filter((file) => file.endsWith('.svg'))
    .sort()
    .map((file) => basename(file, '.svg'))
    .map((name) => ({
      name,
      pascalName: toPascalCase(name),
      bodies: Object.fromEntries(WEIGHTS.map((weight) => [weight, readIconBody(name, weight)])) as IconSource['bodies'],
    }))
}

function renderIconModule({ name, pascalName, bodies }: IconSource): string {
  const tag = `${TAG_PREFIX}${name}`
  const cases = WEIGHTS.map((weight) => `case '${weight}': return svg\`${toTemplateLiteralBody(bodies[weight])}\``).join('\n')
  return `${header}
import { svg } from 'lit'
import { customElement } from 'lit/decorators.js'
import { PhosphorIcon, type PhosphorIconWeight } from '../phosphor-icon'

/**
 * Phosphor \`${name}\` icon.
 *
 * @tag ${tag}
 *
 * @cssproperty {pixel} [--c2-phosphor-icon--size=24px]
 * @cssproperty {color} [--c2-phosphor-icon--color=currentColor]
 */
@customElement('${tag}')
export class Phosphor${pascalName}Icon extends PhosphorIcon {
  protected override renderIcon(weight: PhosphorIconWeight) {
    switch (weight) {
      ${cases}
    }
  }
}

declare global {
  interface HTMLElementTagNameMap {
    '${tag}': Phosphor${pascalName}Icon
  }
}
`
}

function renderIndexModule(iconSources: IconSource[]): string {
  const exports = iconSources.map(({ name }) => `export * from './icons/${name}'`).join('\n')
  return `${header}
// Importing this barrel registers every Phosphor icon element. Prefer importing
// individual icons (\`@c2n/phosphor-icons/icons/<name>.js\`) in production bundles.
export * from './phosphor-icon'
export * from './icon-names'
${exports}
`
}

function renderIconNamesModule(iconSources: IconSource[]): string {
  const names = iconSources.map(({ name }) => `'${name}'`).join(', ')
  return `${header}
export const phosphorIconTagPrefix = '${TAG_PREFIX}'
export const phosphorIconSource = {
  package: '@phosphor-icons/core',
  version: '${upstreamVersion}',
  label: '${sourceLabel}',
} as const

export const phosphorIconNames = [${names}] as const

export type PhosphorIconName = (typeof phosphorIconNames)[number]

/** Custom element tag name for a Phosphor icon, e.g. \`airplane\` -> \`${TAG_PREFIX}airplane\`. */
export function phosphorIconTag(name: PhosphorIconName): \`${TAG_PREFIX}\${PhosphorIconName}\` {
  return \`${TAG_PREFIX}\${name}\`
}
`
}

async function writeFormatted(filePath: string, code: string): Promise<void> {
  const config = (await resolveConfig(filePath)) ?? {}
  const formatted = await format(code, { ...config, filepath: filePath })
  writeFileSync(filePath, formatted)
}

async function main(): Promise<void> {
  const iconSources = readIconSources()
  if (iconSources.length === 0) throw new Error('[icon-generator] no Phosphor icons found')

  rmSync(iconsOutDir, { recursive: true, force: true })
  mkdirSync(iconsOutDir, { recursive: true })

  await Promise.all([
    ...iconSources.map((icon) => writeFormatted(join(iconsOutDir, `${icon.name}.ts`), renderIconModule(icon))),
    writeFormatted(join(srcDir, 'index.ts'), renderIndexModule(iconSources)),
    writeFormatted(join(srcDir, 'icon-names.ts'), renderIconNamesModule(iconSources)),
  ])

  console.log(`[icon-generator] Generated ${iconSources.length} icons in ${WEIGHTS.length} weights from ${sourceLabel}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
