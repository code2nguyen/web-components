/**
 * Emoji data generator for `@c2n/emoji-picker`.
 *
 * Reads the English data set of the `emojibase-data` devDependency and writes `src/emoji-data.ts`: every emoji up to
 * `MAX_VERSION` (newer ones still draw as a blank box on many systems), in Unicode order, grouped by category, with
 * its name, its search keywords and its five skin-tone variants when it has them. The data is one tab-separated string
 * per category rather than an array of objects, which keeps the module about half the size; `src/emoji-data.ts`
 * parses it once, on first use.
 *
 * Run with `npm run generate -w packages/components/emoji-picker` after bumping `emojibase-data`, and commit the
 * result. Node 24 type stripping: erasable TypeScript only.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

/** The newest Emoji version the set includes. 15.1 (2023) draws on every current system. */
const MAX_VERSION = 15.1

interface Skin {
  emoji: string
  tone?: number | number[]
}

interface Emoji {
  label: string
  emoji: string
  group?: number
  order?: number
  version: number
  tags?: string[]
  skins?: Skin[]
}

const require = createRequire(import.meta.url)
const data: Emoji[] = require('emojibase-data/en/data.json')
const meta: { groups: Record<string, string> } = require('emojibase-data/meta/groups.json')
const emojibaseVersion: string = require('emojibase-data/package.json').version

const here = dirname(fileURLToPath(import.meta.url))
const target = resolve(here, '../../src/emoji-data.ts')

/** A field may not hold the separators the encoded string uses. */
const clean = (text: string) => text.replace(/[\t\n]/g, ' ').trim()

/** The variant of each of the five tones, or none when the emoji has no single-tone variant for every tone. */
function skinVariants(skins: Skin[] | undefined): string[] {
  if (!skins) return []
  const variants = [1, 2, 3, 4, 5].map(
    (tone) => skins.find((skin) => skin.tone === tone || (Array.isArray(skin.tone) && skin.tone.every((part) => part === tone)))?.emoji,
  )
  return variants.every((variant): variant is string => !!variant) ? variants : []
}

const groups = new Map<string, string[]>()
for (const emoji of [...data].sort((a, b) => (a.order ?? 0) - (b.order ?? 0))) {
  const group = emoji.group === undefined ? undefined : meta.groups[String(emoji.group)]
  if (!group || group === 'component' || emoji.version > MAX_VERSION) continue
  const nameWords = new Set(emoji.label.toLowerCase().split(/[^\p{L}\p{N}]+/u))
  const keywords = [...new Set((emoji.tags ?? []).map((tag) => clean(tag.toLowerCase())))].filter((tag) => tag && !nameWords.has(tag))
  const line = [emoji.emoji, clean(emoji.label), keywords.join(' '), skinVariants(emoji.skins).join(' ')].join('\t').replace(/\t+$/, '')
  if (!groups.has(group)) groups.set(group, [])
  groups.get(group)!.push(line)
}

const entries = [...groups].map(([group, lines]) => `  ${JSON.stringify(group)}: ${JSON.stringify(lines.join('\n'))},`).join('\n')
const source = `// Generated by scripts/emoji-data-generator from emojibase-data ${emojibaseVersion} (MIT); do not edit.
// Emoji up to version ${MAX_VERSION}. Each category is one string: a line per emoji of
// emoji, name, space-separated keywords and the five skin-tone variants, separated by tabs.

/** The categories of the default set, in the order the picker lists them. */
export const EMOJI_GROUPS = ${JSON.stringify([...groups.keys()])} as const

export const ENCODED_EMOJI: Record<(typeof EMOJI_GROUPS)[number], string> = {
${entries}
}
`

const config = (await resolveConfig(target)) ?? {}
writeFileSync(target, await format(source, { ...config, filepath: target }))
const count = [...groups.values()].reduce((sum, lines) => sum + lines.length, 0)
console.log(`[emoji-data] ${count} emoji in ${groups.size} categories → ${target} (${(readFileSync(target).length / 1024).toFixed(0)} kB)`)
