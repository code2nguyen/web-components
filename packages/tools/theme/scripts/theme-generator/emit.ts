/**
 * Renders `tokens.css`, `base.css`, `theme.css`, `tokens.json` and `report.json` from the token table and
 * the classified component variables.
 */
import { format, resolveConfig } from 'prettier'
import type { TokenDef } from '../../src/tokens.ts'
import type { Classification } from './classify.ts'
import type { CssVar } from './manifests.ts'

export interface ClassifiedVar {
  cssVar: CssVar
  result: Classification
}

const GENERATED = '/* GENERATED by @c2n/theme scripts/theme-generator. Do not edit by hand. */'

function declarations(entries: [string, string][], indent = '  '): string {
  return entries.map(([name, value]) => `${indent}${name}: ${value};`).join('\n')
}

export function renderTokensCss(tokens: TokenDef[]): string {
  const light = tokens.filter((tk) => tk.light !== null).map((tk): [string, string] => [tk.name, tk.light as string])
  const dark = tokens.filter((tk) => tk.dark !== undefined).map((tk): [string, string] => [tk.name, tk.dark as string])
  return `${GENERATED}
/*
 * Design tokens of @c2n/theme. Light values on the root, dark values under [data-theme='dark'] / .c2-dark and
 * as the OS preference fallback. Override any token on :root (or on a subtree) to theme every component.
 */
:root,
:host,
[data-theme='light'],
.c2-light {
  color-scheme: light;
${declarations(light)}
}

[data-theme='dark'],
.c2-dark {
  color-scheme: dark;
${declarations(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']):not(.c2-light) {
    color-scheme: dark;
${declarations(dark, '    ')}
  }
}
`
}

export function renderBaseCss(classified: ClassifiedVar[]): string {
  const byPackage = new Map<string, [string, string][]>()
  for (const { cssVar, result } of classified) {
    if (result.kind !== 'mapped') continue
    const list = byPackage.get(cssVar.pkg) ?? []
    list.push([cssVar.name, result.value])
    byPackage.set(cssVar.pkg, list)
  }
  const blocks = [...byPackage.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([pkg, entries]) => `/* ${pkg} */\n:root,\n:host {\n${declarations(entries)}\n}`)
  return `${GENERATED}
/*
 * Base theme: maps every @c2n component CSS variable onto the --c2-theme--* tokens, keeping the component's
 * original default as the innermost fallback. Setting a component variable yourself always wins.
 */
${blocks.join('\n\n')}
`
}

export interface TokensJson {
  tokens: TokenDef[]
  /** Component variable name → primary token it follows. */
  mapping: Record<string, string>
}

export function buildTokensJson(tokens: TokenDef[], classified: ClassifiedVar[]): TokensJson {
  const mapping: Record<string, string> = {}
  for (const { cssVar, result } of classified) if (result.kind === 'mapped') mapping[cssVar.name] = result.token
  return { tokens, mapping }
}

export interface ReportEntry {
  name: string
  type?: string
  default?: string
  rule: string
  reason: string
}

export interface PackageReport {
  total: number
  mapped: number
  unmapped: number
  excluded: number
  noDefault: number
  unmappedVars: ReportEntry[]
  excludedVars: ReportEntry[]
}

export function buildReport(
  classified: ClassifiedVar[],
  unparsed: string[],
): { packages: Record<string, PackageReport>; totals: Omit<PackageReport, 'unmappedVars' | 'excludedVars'>; unparsed: string[] } {
  const packages: Record<string, PackageReport> = {}
  const totals = { total: 0, mapped: 0, unmapped: 0, excluded: 0, noDefault: 0 }
  for (const { cssVar, result } of classified) {
    const report = (packages[cssVar.pkg] ??= { total: 0, mapped: 0, unmapped: 0, excluded: 0, noDefault: 0, unmappedVars: [], excludedVars: [] })
    report.total++
    totals.total++
    const entry: ReportEntry = {
      name: cssVar.name,
      type: cssVar.type,
      default: cssVar.default,
      rule: result.rule,
      reason: result.kind === 'mapped' ? result.token : result.reason,
    }
    if (result.kind === 'mapped') {
      report.mapped++
      totals.mapped++
    } else if (result.kind === 'excluded') {
      report.excluded++
      totals.excluded++
      report.excludedVars.push(entry)
    } else if (result.rule === 'R1') {
      report.noDefault++
      totals.noDefault++
    } else {
      report.unmapped++
      totals.unmapped++
      report.unmappedVars.push(entry)
    }
  }
  return { packages, totals, unparsed }
}

export async function formatCss(filePath: string, css: string): Promise<string> {
  const config = (await resolveConfig(filePath)) ?? {}
  return format(css, { ...config, parser: 'css' })
}
